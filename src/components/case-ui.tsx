import { Link, useNavigate } from "@tanstack/react-router";
import { FolderOpen, Info, Pencil, Check, Loader2 } from "lucide-react";
import { useState, type ReactNode } from "react";
import { Button } from "@/components/ui/button";
import { Textarea } from "@/components/ui/textarea";
import { useCase } from "@/lib/case-store";
import type { Case } from "@/lib/case";

export function PageHeader({ eyebrow, title, intro }: { eyebrow?: string; title: string; intro?: string }) {
  return (
    <div className="mb-8">
      {eyebrow && <p className="text-sm font-semibold uppercase tracking-wider text-accent">{eyebrow}</p>}
      <h1 className="mt-1 text-3xl font-semibold md:text-4xl">{title}</h1>
      {intro && <p className="mt-3 max-w-2xl text-muted-foreground">{intro}</p>}
    </div>
  );
}

export function SampleNotice() {
  return (
    <div className="mb-6 flex items-start gap-3 rounded-xl border border-border bg-teal-soft p-4 text-sm">
      <Info className="mt-0.5 h-4 w-4 shrink-0 text-accent" aria-hidden />
      <p>
        <strong>Fictional sample case.</strong> This content was written in advance as an example — it was not generated by
        an AI model. Everything is editable.
      </p>
    </div>
  );
}

export function Loading() {
  return (
    <div className="flex items-center justify-center gap-2 py-24 text-muted-foreground" role="status">
      <Loader2 className="h-5 w-5 animate-spin" aria-hidden /> Loading your case…
    </div>
  );
}

export function EmptyCase() {
  const { loadSample } = useCase();
  const navigate = useNavigate();
  return (
    <div className="card-soft mx-auto max-w-lg p-10 text-center">
      <FolderOpen className="mx-auto h-10 w-10 text-accent" aria-hidden />
      <h2 className="mt-4 text-2xl font-semibold">No case open yet</h2>
      <p className="mt-2 text-muted-foreground">Start your own case or explore a complete fictional example.</p>
      <div className="mt-6 flex flex-wrap justify-center gap-3">
        <Button asChild>
          <Link to="/intake">Start my own case</Link>
        </Button>
        <Button
          variant="outline"
          onClick={() => {
            loadSample();
            navigate({ to: "/dashboard" });
          }}
        >
          Try a sample case
        </Button>
      </div>
    </div>
  );
}

/** Renders children only when a case is loaded; otherwise loading / empty states. */
export function WithCase({ children }: { children: (c: Case) => ReactNode }) {
  const { current, ready } = useCase();
  if (!ready) return <Loading />;
  if (!current) return <EmptyCase />;
  return (
    <>
      {current.isSample && <SampleNotice />}
      {children(current)}
    </>
  );
}

export function EditableText({ value, onSave, label, rows = 3 }: { value: string; onSave: (v: string) => void; label: string; rows?: number }) {
  const [editing, setEditing] = useState(false);
  const [draft, setDraft] = useState(value);
  if (editing)
    return (
      <div className="space-y-2">
        <Textarea aria-label={label} rows={rows} value={draft} onChange={(e) => setDraft(e.target.value)} />
        <div className="flex gap-2">
          <Button size="sm" onClick={() => { onSave(draft); setEditing(false); }}>
            <Check className="h-4 w-4" /> Save
          </Button>
          <Button size="sm" variant="ghost" onClick={() => { setDraft(value); setEditing(false); }}>Cancel</Button>
        </div>
      </div>
    );
  return (
    <div className="group flex items-start justify-between gap-3">
      <p className="whitespace-pre-line">{value || <span className="text-muted-foreground">Nothing added yet.</span>}</p>
      <Button size="sm" variant="ghost" aria-label={`Edit ${label}`} onClick={() => { setDraft(value); setEditing(true); }}>
        <Pencil className="h-4 w-4" />
      </Button>
    </div>
  );
}

export function EditableList({ items, onChange, label }: { items: string[]; onChange: (v: string[]) => void; label: string }) {
  return (
    <div className="space-y-3">
      {items.length === 0 && <p className="text-sm text-muted-foreground">Nothing here yet.</p>}
      {items.map((it, i) => (
        <div key={i} className="rounded-lg bg-muted/60 p-3">
          <EditableText label={`${label} ${i + 1}`} value={it} rows={2}
            onSave={(v) => onChange(v.trim() ? items.map((x, j) => (j === i ? v : x)) : items.filter((_, j) => j !== i))} />
        </div>
      ))}
      <Button size="sm" variant="outline" onClick={() => onChange([...items, "New item — click the pencil to edit"])}>+ Add {label.toLowerCase()}</Button>
    </div>
  );
}
